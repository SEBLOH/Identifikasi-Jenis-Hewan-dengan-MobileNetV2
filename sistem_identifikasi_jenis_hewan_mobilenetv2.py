def immediate_image_dirs(root):
    result = []
    try:
        children = os.listdir(root)
    except Exception:
        return result

    for child in children:
        child_path = os.path.join(root, child)

        if not os.path.isdir(child_path):
            continue

        try:
            files = os.listdir(child_path)
        except Exception:
            continue

        if any(
            f.lower().endswith(IMAGE_EXTENSIONS)
            for f in files
        ):
            result.append(child)

    return result

