"""## 5.4 Model Detector Hewan vs Bukan Hewan"""

gate_augmentation = tf.keras.Sequential([
    tf.keras.layers.RandomFlip("horizontal"),
    tf.keras.layers.RandomRotation(0.05),
    tf.keras.layers.RandomZoom(0.08),
    tf.keras.layers.RandomContrast(0.08)
])

gate_base_model = tf.keras.applications.MobileNetV2(
    input_shape=(224, 224, 3),
    include_top=False,
    weights="imagenet"
)

gate_base_model.trainable = False

gate_inputs = tf.keras.Input(shape=(224, 224, 3))

x = gate_augmentation(gate_inputs)
x = tf.keras.layers.Rescaling(1./127.5, offset=-1)(x)
x = gate_base_model(x, training=False)
x = tf.keras.layers.GlobalAveragePooling2D()(x)
x = tf.keras.layers.Dropout(0.30)(x)
x = tf.keras.layers.Dense(128, activation="relu")(x)
x = tf.keras.layers.Dropout(0.20)(x)

gate_outputs = tf.keras.layers.Dense(
    1,
    activation="sigmoid"
)(x)

gate_model = tf.keras.Model(
    gate_inputs,
    gate_outputs,
    name="animal_detector"
)

gate_model.compile(
    optimizer=tf.keras.optimizers.Adam(
        learning_rate=0.001
    ),
    loss="binary_crossentropy",
    metrics=["accuracy"]
)

