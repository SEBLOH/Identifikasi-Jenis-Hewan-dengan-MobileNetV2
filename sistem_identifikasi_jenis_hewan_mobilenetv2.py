def prepare_input_image(
    image,
    image_size=IMG_SIZE
):
    image = image.convert("RGB")
    image = image.resize(image_size)

    image_array = np.array(
        image,
        dtype=np.float32
    )

    return np.expand_dims(
        image_array,
        axis=0
    )


def predict_animal_image(
    image,
    top_k=5
):
    image_array = prepare_input_image(image)

    non_animal_probability = float(
        gate_model.predict(
            image_array,
            verbose=0
        )[0][0]
    )

    animal_probability = (
        1.0 - non_animal_probability
    )

    threshold = globals().get("DETECTOR_THRESHOLD", 0.551)

    if non_animal_probability >= threshold:
        return {
            "status": "Bukan Hewan",
            "confidence": non_animal_probability,
            "predictions": []
        }

    probabilities = model.predict(
        image_array,
        verbose=0
    )[0]

    top_indices = np.argsort(
        probabilities
    )[::-1][:top_k]

    predictions = [
        {
            "class": class_mapping[
                class_names[i]
            ],
            "confidence": float(
                probabilities[i]
            )
        }
        for i in top_indices
    ]

    return {
        "status": "Hewan",
        "confidence": animal_probability,
        "predictions": predictions
    }

